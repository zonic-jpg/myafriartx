#!/usr/bin/env node
// Regenerates the outreach-artist seed artefacts from the curated CSV so the
// data in the app and in the migration can never drift from the source file:
//
//   data/nigerian-artists-outreach-100.csv
//     -> src/lib/outreach-artists.data.ts   (browser/admin seed payload)
//     -> supabase/migrations/20261002000000_outreach_artists.sql  (schema + seed)
//
// Only columns present in the CSV are emitted. Anything the CSV does not know
// (bio, date of birth, gender, portrait, prices) stays NULL — these are real
// people and the seed must not invent facts about them.
//
// Usage: node scripts/gen-outreach-artists.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CSV_PATH = resolve(root, "data/nigerian-artists-outreach-100.csv");
const DATA_OUT = resolve(root, "src/lib/outreach-artists.data.ts");
// Timestamped after every existing migration so `supabase db push` picks it up
// without needing --include-all.
const MIGRATION_OUT = resolve(root, "supabase/migrations/20261002000000_outreach_artists.sql");
const CSV_REL = "data/nigerian-artists-outreach-100.csv";

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        field += ch;
      }
      continue;
    }
    if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.some((c) => c.trim() !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((c) => c.trim() !== "")) rows.push(row);
  return rows;
}

const rows = parseCsv(readFileSync(CSV_PATH, "utf8"));
const header = rows[0].map((h) => h.trim());
const records = rows
  .slice(1)
  .map((cells) => Object.fromEntries(header.map((key, i) => [key, (cells[i] ?? "").trim()])));

// The CSV advertises /artist/<code> URLs; the code is the artist short_code.
const codeFromUrl = (url) => {
  const match = /\/artist\/([A-Za-z0-9-]+)\s*$/.exec(url ?? "");
  return match ? match[1].toUpperCase() : "";
};

const seeds = records.map((r, index) => {
  const shortCode = codeFromUrl(r.myafriart_profile_url);
  if (!shortCode) throw new Error(`Row ${index + 2}: no artist code in myafriart_profile_url`);
  if (!r.name) throw new Error(`Row ${index + 2}: missing name`);
  return {
    short_code: shortCode,
    name: r.name,
    primary_medium: r.medium || null,
    domicile_city: r.city || null,
    country: r.country || null,
    website: r.website || null,
    outreach_note: r.notes || null,
    outreach_source: r.source || null,
    outreach_status: r.outreach_status || null,
  };
});

const codes = new Set(seeds.map((s) => s.short_code));
if (codes.size !== seeds.length) throw new Error("Duplicate artist codes in CSV");

const banner = (
  comment,
) => `${comment} Generated by scripts/gen-outreach-artists.mjs from ${CSV_REL}.
${comment} Do not edit by hand — update the CSV and re-run the generator.
${comment} Only CSV-backed facts are seeded; unknown fields stay NULL.`;

// ── TypeScript payload ──────────────────────────────────────────────────────
const tsLiteral = (v) => (v === null ? "null" : JSON.stringify(v));
const tsRows = seeds
  .map(
    (s) => `  {
    short_code: ${tsLiteral(s.short_code)},
    name: ${tsLiteral(s.name)},
    primary_medium: ${tsLiteral(s.primary_medium)},
    domicile_city: ${tsLiteral(s.domicile_city)},
    country: ${tsLiteral(s.country)},
    website: ${tsLiteral(s.website)},
    outreach_note: ${tsLiteral(s.outreach_note)},
    outreach_source: ${tsLiteral(s.outreach_source)},
    outreach_status: ${tsLiteral(s.outreach_status)},
  },`,
  )
  .join("\n");

writeFileSync(
  DATA_OUT,
  `${banner("//")}

export type OutreachArtistSeed = {
  short_code: string;
  name: string;
  primary_medium: string | null;
  domicile_city: string | null;
  country: string | null;
  website: string | null;
  outreach_note: string | null;
  outreach_source: string | null;
  outreach_status: string | null;
};

export const OUTREACH_ARTIST_SEEDS: OutreachArtistSeed[] = [
${tsRows}
];
`,
);

// ── SQL migration ───────────────────────────────────────────────────────────
const sqlLiteral = (v) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const sqlRows = seeds
  .map(
    (s) =>
      `  (${[
        s.short_code,
        s.name,
        s.primary_medium,
        s.domicile_city,
        s.country,
        s.website,
        s.outreach_note,
        s.outreach_source,
        s.outreach_status,
      ]
        .map(sqlLiteral)
        .join(", ")}, 'unclaimed_outreach', 'outreach')`,
  )
  .join(",\n");

writeFileSync(
  MIGRATION_OUT,
  `${banner("--")}
--
-- Outreach artist profiles: real Nigerian artists we are reaching out to. They
-- are NOT paying members, so they carry profile_status = 'unclaimed_outreach'
-- and content_source = 'outreach' to keep them out of the curated allocation
-- lanes while still being browsable and addressable at /artist/<short_code>.

alter table public.artists
  add column if not exists profile_status text not null default 'active',
  add column if not exists primary_medium text,
  add column if not exists website text,
  add column if not exists outreach_note text,
  add column if not exists outreach_source text,
  add column if not exists outreach_status text;

comment on column public.artists.profile_status is
  'active = onboarded artist; unclaimed_outreach = curated outreach record, not a member.';
comment on column public.artists.outreach_note is
  'Verbatim curator note from the outreach CSV. Never an artist-authored bio.';

do $$ begin
  alter table public.artists add constraint artists_profile_status_chk
    check (profile_status in ('active', 'unclaimed_outreach'));
exception when duplicate_object then null; end $$;

-- 'outreach' joins the existing content_source buckets. Both historical check
-- constraints are replaced by a single up-to-date one.
alter table public.artists drop constraint if exists artists_content_source_check;
alter table public.artists drop constraint if exists artists_content_source_chk;
alter table public.artists
  add constraint artists_content_source_chk
  check (content_source in ('live', 'mock', 'artstage', 'outreach'));

create index if not exists idx_artists_profile_status on public.artists(profile_status);
create index if not exists idx_artists_primary_medium on public.artists(primary_medium);

insert into public.artists (
  short_code, name, primary_medium, domicile_city, country, website,
  outreach_note, outreach_source, outreach_status, profile_status, content_source
) values
${sqlRows}
on conflict (short_code) do update set
  name = excluded.name,
  primary_medium = excluded.primary_medium,
  domicile_city = excluded.domicile_city,
  country = excluded.country,
  website = excluded.website,
  outreach_note = excluded.outreach_note,
  outreach_source = excluded.outreach_source,
  outreach_status = excluded.outreach_status,
  profile_status = excluded.profile_status,
  content_source = excluded.content_source;
`,
);

console.log(`Generated ${seeds.length} outreach artists`);
console.log(`  ${DATA_OUT}`);
console.log(`  ${MIGRATION_OUT}`);
